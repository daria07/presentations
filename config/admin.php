<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Кто пускается в кабинет администратора
    |--------------------------------------------------------------------------
    | Список адресов через запятую в ADMIN_EMAILS. Права живут в окружении,
    | а не в базе: строку в users можно выставить случайной миграцией,
    | сидом или дырой в приложении, а .env на сервере меняют руками.
    |
    | Пустой список означает, что кабинета нет ни у кого — так и должно
    | быть по умолчанию на новой машине.
    */

    'emails' => array_values(array_filter(array_map(
        fn (string $email) => mb_strtolower(trim($email)),
        explode(',', (string) env('ADMIN_EMAILS', '')),
    ))),

    /*
    |--------------------------------------------------------------------------
    | Часовой пояс сводки
    |--------------------------------------------------------------------------
    | Приложение и база живут в UTC, а «сегодня» в админке — это сегодня
    | по Москве: иначе в 01:30 ночи «сегодня» показывало бы ещё вчерашний
    | день, а регистрации около полуночи падали бы не в те сутки.
    */

    'timezone' => env('ADMIN_TIMEZONE', 'Europe/Moscow'),

];
